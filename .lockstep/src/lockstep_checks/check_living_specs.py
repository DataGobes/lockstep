"""Keep the living specs current: ``specs/living/<capability>.md``, one per capability, generated from the specs.

A spec says what changes; a living spec says what is true now. Each spec names its capability in status.yml
(``capability: churn-scoring``). The living spec of a capability lists the active criteria of its specs: tests-locked
or implemented ones as "In force", approved ones as "Coming". A spec reaches main tests-locked only together with its
green implementation (the test PR merges into the feature branch), so on main "In force" is what the code does. A criterion struck and superseded drops
out, so the file always shows the current behaviour, while tests keep naming criteria by their spec (0042/AC-001).

Off unless ``[specs] living = true``. Then this check fails a PR whose living specs are stale, a generated file whose
capability has no specs left, or a spec past draft without a capability. ``--write`` regenerates the files.
Living specs come from SDTRD (``specs/living/``); Lockstep generates them instead of copying specs over them.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

from .cli import run
from .config import Config
from .report import Finding
from .spec import SpecError, list_specs, load_status
from .specdoc import parse_spec
from .status import SpecStatus

HEADER = "<!-- Generated by lockstep_checks.check_living_specs --write. Do not edit: change a spec instead. -->"
LIVING_DIR = "living"


@dataclass(frozen=True)
class Entry:
    spec_id: str
    title: str
    path: str  # spec.md, relative to the living folder
    status: SpecStatus
    criteria: list[list[str]]  # each active criterion's lines


def living_dir(root: Path, cfg: Config) -> Path:
    return root / cfg.specs_dir / LIVING_DIR


def collect(root: Path, cfg: Config) -> tuple[dict[str, list[Entry]], list[Finding]]:
    by_capability: dict[str, list[Entry]] = {}
    findings = []
    for spec_id, spec_dir in list_specs(root, cfg).items():
        status = load_status(root, spec_dir, cfg)
        if status.status == "draft":
            continue
        if status.capability is None:
            msg = "names no capability; add `capability: <name>` to status.yml so its criteria reach a living spec"
            findings.append(
                Finding("error", f"spec {spec_id} {msg}", (spec_dir / "status.yml").relative_to(root).as_posix())
            )
            continue
        try:
            text = (spec_dir / "spec.md").read_text(encoding="utf-8")
        except FileNotFoundError:
            continue  # check_ac_traceability reports it
        doc = parse_spec(text, cfg.specs.ac_format)
        entry = Entry(
            spec_id, _title(text, spec_dir.name), f"../{spec_dir.name}/spec.md", status, list(doc.text.values())
        )
        by_capability.setdefault(status.capability, []).append(entry)
    return by_capability, findings


def render(capability: str, entries: list[Entry]) -> str:
    out = [
        HEADER,
        "",
        f"# {capability}",
        "",
        "What this capability does now: the active acceptance criteria of every spec that names it. Superseded",
        "criteria are left out. Tests name each criterion by its spec, as listed.",
    ]
    for heading, states in (("In force", ("tests-locked", "implemented")), ("Coming", ("approved",))):
        group = [e for e in entries if e.status.status in states]
        if not group:
            continue
        out += ["", f"## {heading}"]
        for e in sorted(group, key=lambda e: e.spec_id):
            out += ["", f"### [{e.spec_id} {e.title}]({e.path}) ({e.status.status})", ""]
            for lines in e.criteria:
                first, *steps = lines
                out.append(f"- {e.spec_id}/{first.lstrip('-* ')}")
                out += [f"  {step}" for step in steps]
            if not e.criteria:
                out.append("- no active criteria")
    return "\n".join(out) + "\n"


def check_living_specs(root: Path, cfg: Config, write: bool = False) -> list[Finding]:
    if not cfg.specs.living:
        return []
    try:
        by_capability, findings = collect(root, cfg)
    except SpecError as e:
        return [Finding("error", str(e))]
    folder = living_dir(root, cfg)
    wanted = {folder / f"{c}.md": render(c, entries) for c, entries in by_capability.items()}
    generated = {p for p in folder.glob("*.md") if _is_generated(p)} if folder.is_dir() else set()
    fix = "run `python -m lockstep_checks.check_living_specs --write` and commit the result"
    for path, text in sorted(wanted.items()):
        rel = path.relative_to(root).as_posix()
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if current is not None and not current.startswith(HEADER):
            findings.append(Finding("error", f"{rel} exists but was not generated; move it, then {fix}", rel))
        elif write:
            folder.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
        else:
            findings.append(Finding("error", f"{rel} is {'missing' if current is None else 'out of date'}; {fix}", rel))
    for path in sorted(generated - set(wanted)):
        rel = path.relative_to(root).as_posix()
        if write:
            path.unlink()
            print(f"removed {rel}")
        else:
            findings.append(Finding("error", f"{rel}: no spec names this capability any more; {fix}", rel))
    return findings


def _is_generated(path: Path) -> bool:
    with path.open(encoding="utf-8") as f:
        return f.readline().rstrip("\n") == HEADER


def _title(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("title:"):
            return line.removeprefix("title:").strip() or fallback
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    write = "--write" in argv
    if write:
        argv.remove("--write")
    return run(
        "check_living_specs",
        __doc__.splitlines()[0] + " Add --write to regenerate them.",
        lambda ctx: check_living_specs(ctx.root, ctx.cfg, write),
        argv,
    )


if __name__ == "__main__":
    sys.exit(main())
